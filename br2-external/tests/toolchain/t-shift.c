int main(void)
{
	unsigned int i, n;
	uint32_t sum = 0;

	for (i = 0; i < sizeof(t32) / sizeof(t32[0]); i++) {
		volatile uint32_t v = t32[i].v;
		volatile unsigned int c = t32[i].n;
		volatile int32_t sv = (int32_t)t32[i].v;

		CHECK((uint32_t)(v << c) == t32[i].shl);
		CHECK((uint32_t)(v >> c) == t32[i].shr);
		CHECK((int32_t)(sv >> c) == t32[i].sar);
		sum = sum * 31 + t32[i].shl;
		sum = sum * 31 + t32[i].shr;
		sum = sum * 31 + (uint32_t)t32[i].sar;
	}
	for (i = 0; i < sizeof(t64) / sizeof(t64[0]); i++) {
		volatile uint64_t v = t64[i].v;
		volatile unsigned int c = t64[i].n;
		volatile int64_t sv = (int64_t)t64[i].v;

		CHECK((uint64_t)(v << c) == t64[i].shl);
		CHECK((uint64_t)(v >> c) == t64[i].shr);
		CHECK((int64_t)(sv >> c) == t64[i].sar);
	}

	/* Every count from 0 to 31 and 0 to 63 against doubling and halving. */
	for (n = 0; n < 32; n++) {
		volatile unsigned int c = n;
		uint32_t want = 3;
		unsigned int k;

		for (k = 0; k < n; k++)
			want *= 2;
		CHECK((3u << c) == want);
	}
	for (n = 0; n < 64; n++) {
		volatile unsigned int c = n;
		uint64_t want = 0x8000000000000003ULL, got = 0x8000000000000003ULL;
		unsigned int k;

		for (k = 0; k < n; k++)
			want /= 2;
		CHECK((got >> c) == want);
	}
	printf("%lu\n", (unsigned long)sum);
	DONE("shift");
}
